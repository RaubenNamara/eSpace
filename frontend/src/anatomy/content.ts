/** "Left femur" / "right-lung" -> "femur" / "lung"; vessel names fold to their family */
export function contentKey(nameOrSlug: string): string {
  let k = nameOrSlug.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')
  k = k.replace(/^(left|right)-/, '')
  if (k === 'superior-vena-cava' || k === 'inferior-vena-cava') return 'vena-cava'
  if (k === 'left-cerebral-hemisphere' || k === 'right-cerebral-hemisphere') return 'cerebral-hemisphere'
  if (k === 'testis' || k === 'testes') return 'testis'
  return k
}

export function contentFor(nameOrSlug: string): OrganContent | null {
  return CONTENT[contentKey(nameOrSlug)] ?? null
}
